"""Generate the per-surface list-coverage page from the signed seed.

The same list is not enforced everywhere, and the tiers are not
interchangeable. This page is generated so a release cannot claim a client
carries the full list when it only bundles the core tier. `--check` fails when
the page or the static ruleset disagrees with the signed seed.

    python3 script/coverage.py           # rewrite docs/COVERAGE.md
    python3 script/coverage.py --check   # fail on drift
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED = ROOT / "seed/manifest.json"
EXTENSION_RULES = ROOT / "extension/rules/dnr_block_rules.json"
DOC = ROOT / "docs/COVERAGE.md"
SAFARI_BLOCKERS = 6
SAFARI_CAPACITY = 40_000


def facts():
    seed = json.loads(SEED.read_text())
    rules = json.loads(EXTENSION_RULES.read_text())
    if not isinstance(rules, list):
        raise ValueError("extension/rules/dnr_block_rules.json is not a list")
    core, full = seed["core_domain_count"], seed["domain_count"]
    if not 0 < core <= full:
        raise ValueError(f"seed counts are not ordered: core {core}, full {full}")
    if core > SAFARI_BLOCKERS * SAFARI_CAPACITY:
        raise ValueError(f"core tier {core:,} does not fit six Safari blockers")
    if "core_capacity" in seed and core > seed["core_capacity"]:
        raise ValueError(f"core tier {core:,} exceeds the signed capacity {seed['core_capacity']:,}")
    if len(rules) != seed["dnr_rule_count"]:
        raise ValueError(f"{len(rules)} static DNR rules, manifest says {seed['dnr_rule_count']}")
    return seed, len(rules)


def document():
    seed, static_rules = facts()
    core = f"{seed['core_domain_count']:,}"
    full = f"{seed['domain_count']:,}"
    terms = f"{seed['term_count']:,}"
    host_terms = seed["host_term_count"]
    keyword_rules = seed["dnr_keyword_rule_count"]
    safari_capacity = f"{SAFARI_BLOCKERS * SAFARI_CAPACITY:,}"
    headroom = SAFARI_BLOCKERS * SAFARI_CAPACITY - seed["core_domain_count"]
    fill = seed.get("core_fill", {})
    if fill.get("enabled"):
        fill_sources = " and ".join(f"`{s}`" for s in fill["sources"])
        fill_note = (
            f"The extra core domains come from `core_fill`: "
            f"{fill['selected']:,} selected from {fill['eligible']:,} eligible "
            f"domains that both {fill_sources} carry and that also carry an "
            f"adult TLD, a reviewed token, or an IDN label. "
            f"{fill['deferred']:,} eligible domains were deferred by the "
            f"capacity cap; the signed manifest records that number. The "
            f"hand-picked core sources alone collapse to "
            f"{fill['core_sources_collapsed']:,} domains.")
    else:
        fill_note = "No core fill is configured."
    return f"""# Content coverage by surface

> Generated by `script/coverage.py` from the signed seed and the static
> ruleset. Do not edit by hand: run the script after a seed rebuild.

Seed **v{seed['version']}**, built {seed['built_at']}. These counts describe
the bundled starting point, not a promise about every URL a person visits.
Until the `lists` branch publishes a newer generation, every client stays at
this seed; the extension and Mac app state the installed generation and warn
when it is old.

## The three tiers

| Tier | Domains | Where it fits |
| --- | --- | --- |
| Core (bundled) | {core} | The browser extension, the six Safari blockers, the iOS app and the Android DNS seed |
| Full (buildable) | {full} | The Mac socket filter and the network DNS build; publishable to the `lists` branch, not bundled in any client and too large for the browser and Safari tiers |
| Keyword layer | {terms} terms | Page-text scoring in the extension, Safari text extension and Android selected-app checks |

The extension carries **{static_rules} static DNR block rules** and
**{keyword_rules} keyword DNR rules**; the URL rules are collapsed from the
core tier, not one rule per domain. Safari's six blockers hold at most
{safari_capacity} entries together, so the {core}-domain core tier fits with
{headroom:,} entries of headroom.

{fill_note} The full tier also carries the mixed ad/tracker snapshot; it is not
part of the bundled core.

## Per surface

| Surface | Domain tier | Page text | Visual | Short video | Native apps |
| --- | --- | --- | --- | --- | --- |
| Chromium extension | Core · {core} domains, {static_rules} static rules | Yes (language-aware: en/ar/de/es/fr/it/pt, evasion) | Opt-in, hide-first on supported sites | Opt-in (YouTube, Instagram, Facebook, Snapchat, TikTok) | No |
| Mac content filter | Full · {full} domains once a published generation is installed; core seed before that | No native-app text | No | No | All apps at host/flow level |
| Safari on iPhone/iPad | Core · {core} domains in six blockers | Safari text extension | Opt-in local | No | WebKit only |
| Android DNS | Core · {core} domains | Selected apps via accessibility | Selected apps, Android 14+ | Selected apps | Selected apps only |
| Router / network DNS | The resolver's categories, not Hisn's list | No | No | No | Any device on that network |

{host_terms} host terms are also bundled for hosts registered after the
build; they are not a substitute for the domain tier.

## What this table does not claim

- A lower tier is not a bug: the browser and Safari cannot hold the full list
  without exceeding platform rule and blocker limits.
- Domain coverage does not cover page text, images, video, in-app web views,
  encrypted native-app traffic, other browsers, or another device.
- The Mac filter acts on host/flow decisions for all apps, but it cannot read
  the content of an encrypted post.
- A resolver's categories enforce the resolver's list, not Hisn's, and another
  network or a tunnel bypasses it.
- Counts are not a quality measure. A labelled corpus with denominators is the
  text gate; a licensed benchmark is the visual gate. Neither is this page.
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the page is stale or the static rules drifted")
    args = parser.parse_args()
    try:
        content = document()
    except (KeyError, ValueError) as error:
        parser.exit(1, f"Coverage inputs are inconsistent: {error}\n")
    if args.check:
        if not DOC.exists() or DOC.read_text() != content:
            parser.exit(1, "docs/COVERAGE.md is stale; run python3 script/coverage.py\n")
    else:
        DOC.write_text(content)
        print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
