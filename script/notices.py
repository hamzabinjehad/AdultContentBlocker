"""Generate the third-party notices bundled into the iOS and Mac apps.

The Android app has its own runtime screen and `android/check-notices.py`. This
fills the same gap for the Apple apps: every enabled domain-list source, its
licence and upstream URL, the licence texts that are actually redistributed,
and (for iOS) the visual runtime's notices.

    python3 script/notices.py          # rewrite both files
    python3 script/notices.py --check  # fail when a file is stale
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "blocklist/sources.json"
IOS = ROOT / "ios/Hisn/Notices.txt"
MAC = ROOT / "macos/Hisn/Notices.txt"
LICENSES = ROOT / "android/app/src/main/assets/licenses"
VISUAL = ROOT / "extension/visual"

# Upstream licence files used by the bundled core tier. A text is included only
# when it is actually redistributed; the rest point at the upstream terms.
TEXTS = [
    ("StevenBlack/hosts", "MIT", LICENSES / "StevenBlack-hosts-MIT.txt"),
    ("Sinfonietta/hostfiles", "MIT", LICENSES / "Sinfonietta-hostfiles-MIT.txt"),
    ("GNU General Public License 3.0 (hagezi/dns-blocklists, chadmayfield/my-pihole-blocklists)",
     "GPL-3.0", LICENSES / "GPL-3.0.txt"),
    ("LDNOOBW German word list", "CC-BY-4.0", LICENSES / "LDNOOBW-CC-BY-4.0.txt"),
]


def sources():
    data = json.loads(SOURCES.read_text())
    entries = []
    for source in data["sources"]:
        if not source.get("enabled", True):
            continue
        entries.append({
            "id": source["id"],
            "tier": source.get("tier", "extended"),
            "license": source.get("license", "see upstream"),
            "url": source.get("url") or source.get("path", ""),
            "note": source.get("note", ""),
        })
    return sorted(entries, key=lambda entry: entry["id"])


def header(target):
    return f"""Hisn third-party notices — {target}
Generated by script/notices.py. Do not edit by hand.

Hisn is original software. It redistributes domain lists and, in the Safari
text/visual extension, a local visual runtime. Those components remain under
their own licences; nothing here changes Hisn's own terms.

Domain-list sources
===================
"""


def source_section():
    lines = []
    for entry in sources():
        lines.append(f"{entry['id']}  [{entry['tier']}]")
        lines.append(f"  Licence: {entry['license']}")
        lines.append(f"  Upstream: {entry['url']}")
        if entry["note"]:
            lines.append(f"  Note: {entry['note']}")
        lines.append("")
    lines.append("A source marked extended is not bundled in the browser or Safari "
                 "core tier; it is used by the full Mac/DNS list build. The upstream "
                 "terms above still apply to that build.")
    return "\n".join(lines) + "\n"


def license_section():
    lines = ["Licence texts", "=============", ""]
    for name, license_name, path in TEXTS:
        if not path.is_file():
            raise SystemExit(f"notices: missing licence text {path}")
        lines.append(f"--- {name} ({license_name}) ---")
        lines.append(path.read_text().rstrip())
        lines.append("")
    lines.append("The Unlicense and the oisd/UT1 terms are not reproduced here; "
                 "their upstream pages are linked above. The project's own source "
                 "is at https://github.com/hamzabinjehad/AdultContentBlocker.")
    return "\n".join(lines) + "\n"


def visual_section():
    lines = ["Visual runtime notices (Safari/Chromium extension)", "=" * 52, ""]
    legal = VISUAL / "engine.bundle.js.LEGAL.txt"
    if not legal.is_file():
        raise SystemExit(f"notices: missing {legal}")
    lines.append("--- engine bundle legal notice ---")
    lines.append(legal.read_text().rstrip())
    lines.append("")
    notices = sorted((VISUAL / "notices").glob("*"))
    if not notices:
        raise SystemExit("notices: no visual notice files")
    for path in notices:
        lines.append(f"--- {path.name} ---")
        lines.append(path.read_text().rstrip())
        lines.append("")
    return "\n".join(lines) + "\n"


def document(target):
    parts = [header(target), source_section(), license_section()]
    if target == "iOS":
        parts.append(visual_section())
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for target, path in (("iOS", IOS), ("macOS", MAC)):
        content = document(target)
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)} ({len(content):,} bytes)")
    if stale:
        parser.exit(1, "Notices are stale: " + ", ".join(stale) + "; run python3 script/notices.py\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
