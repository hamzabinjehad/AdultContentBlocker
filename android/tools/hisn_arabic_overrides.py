#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Writes app/src/hisn/res/values-ar/wording.xml.

The Islamic edition (Hisn) words two things differently from the general Arabic app, by the
owner's choice: it counts in 1 2 3 rather than Arabic-Indic digits, and it says "الزنا" where the
general app says "الإباحي". Shared Arabic strings that differ are repeated for the hisn flavor only.
Run from android/ after changing main/res/values-ar/strings.xml:

    python3 tools/hisn_arabic_overrides.py

The same rules live in Kotlin as hisnWords() in IslamicCommon.kt for text built in code.
"""
import re
import sys

AR = '[ء-ْٰ]+'
RULES = [
    ('المواقع والبحث والكلمات والصور الإباحية', 'مواقع الزنا وبحثه وكلماته وصوره'),
    ('المواقع والكلمات والصور الإباحية', 'مواقع الزنا وكلماته وصوره'),
    ('الكلمات والوسوم الإباحية', 'كلمات الزنا ووسومه'),
    ('المواقع والصور الإباحية', 'مواقع الزنا وصوره'),
    ('الكلمات والصور الإباحية', 'كلمات الزنا وصوره'),
    ('صفحتان إباحيتان', 'صفحتا زنا'),
    ('موقعًا إباحيًا', 'موقع زنا'),
    ('محتوى إباحياً', 'محتوى زنا'),
    ('بأنها إباحية', 'بأنها للزنا'),
]
REGEX = [
    (re.compile('ال(' + AR + ') الإباحية'), r'\1 الزنا'),
    (re.compile('ال(' + AR + ') الإباحي(?![ء-ي])'), r'\1 الزنا'),
    (re.compile('(' + AR + ') إباحية'), r'\1 زنا'),
    (re.compile('(' + AR + ') إباحي(?![ء-ي])'), r'\1 زنا'),
]
DIGITS = {ord(a): str(i) for i, a in enumerate('٠١٢٣٤٥٦٧٨٩')}
DIGITS[ord('٬')] = ','
DIGITS[ord('٪')] = '%'


def words(t):
    for a, b in RULES:
        t = t.replace(a, b)
    for rx, to in REGEX:
        t = rx.sub(to, t)
    return t


def convert(t):
    return words(t).translate(DIGITS)


def main():
    src = open('app/src/main/res/values-ar/strings.xml', encoding='utf-8').read()
    out = []
    left = []
    for m in re.finditer(r'^[ \t]*<(string|plurals|string-array) name="(\w+)"[^>]*>.*?</\1>[ \t]*$', src, re.S | re.M):
        block = m.group(0)
        new = convert(block)
        if new != block:
            out.append(new)
            if 'إباح' in new:
                left.append(m.group(2))
    body = '\n'.join(out)
    open('app/src/hisn/res/values-ar/wording.xml', 'w', encoding='utf-8').write(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/hisn_arabic_overrides.py: the shared Arabic strings that Hisn words\n'
        '     differently (1 2 3 digits, "الزنا" for "الإباحي"). Do not edit by hand. -->\n'
        '<resources>\n' + body + '\n</resources>\n')
    print(len(out), 'overrides; still holding the old word:', left)
    if '--show' in sys.argv:
        for b in out:
            for line in b.split('\n'):
                if 'زنا' in line:
                    print(re.sub(r'\s+', ' ', line).strip()[:170])


if __name__ == '__main__':
    main()
