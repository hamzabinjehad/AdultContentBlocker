package app.hisn.android.nativeshell

/**
 * Protection-screen copy for the two languages Hisn ships, chosen from the app locale by
 * [protectionCopy]. Moving it into string resources is still open.
 */
data class ProtectionCopy(
    val appName: String,
    val tagline: String,
    val navProtection: String,
    val navRules: String,
    val navSettings: String,
    val protectedTitle: String,
    val protectedBody: String,
    val partialTitle: String,
    val partialBody: String,
    val fixGaps: String,
    val attentionTitle: String,
    val attentionBody: String,
    val runCheck: String,
    val fixNow: String,
    val network: String,
    val apps: String,
    val images: String,
    val tags: String,
    val on: String,
    val off: String,
    val needsAttention: String,
    val dnsStoppedTitle: String,
    val dnsStoppedBody: String,
    val guardOffTitle: String,
    val guardOffBody: String,
    val guardWaitTitle: String,
    val guardWaitBody: String,
    val gapTitle: String,
    val gapBody: String,
    val layers: String,
    val dnsTitle: String,
    val dnsOn: String,
    val dnsOff: String,
    val appTitle: String,
    val appOff: String,
    val appNone: String,
    val appOne: String,
    val appMany: String,
    val tagsTitle: String,
    val tagsOn: String,
    val tagsOff: String,
    val imageTitle: String,
    val imageOn: String,
    val imageOff: String,
    val yourRules: String,
    val domains: String,
    val appsBlocked: String,
    val bypass: String,
    val reassurance: String,
    val checkPassed: String,
    val allArmed: String,
    val undo: String
) {
    fun dnsOnText(domains: Int): String =
        if (domains > 0) dnsOn.replace("{n}", String.format(java.util.Locale.getDefault(), "%,d", domains)) else on

    fun checkText(running: Int, total: Int): String =
        checkPassed.replace("{n}", running.toString()).replace("{t}", total.toString())

    /** "1 app blocked", "3 apps blocked", "No apps selected" — one phrase, not three strings. */
    fun appsBlockedText(count: Int): String = when {
        count <= 0 -> appNone
        count == 1 -> appOne
        else -> appMany.replace("{n}", count.toString())
    }
}

