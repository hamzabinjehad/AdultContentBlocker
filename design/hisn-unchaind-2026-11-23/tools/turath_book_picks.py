def clean(s):
  s=re.sub(r'\s*\(\^?\*?[٠-٩0-9]*\*?\)','',s)
  s=re.sub(r'(?<=[ء-يً-ْ])[٠-٩]+','',s)
  s=re.sub(r'^[٠-٩]+-\s*','',s)
  s=s.replace('القلبالصحيح','الْقلب الصَّحِيح')
  s=s.replace('فَإِن الْقلب','فَإِن الْقلب')
  s=s.replace('القلب ُ،','القلب،').replace(': " ',': ').replace(': "',': ')
  return re.sub(r'[ \t]+',' ',s).strip()
