#!/usr/bin/env python3
"""Unrot mark: the general edition's icon, drawn with hisn_mark.py's renderer.

An ink-blue circle (a head) with a pearl sprout cut out of it: growth after the rot. The cut
pieces (stem, two leaves) touch but never overlap, so the themed-icon silhouette can use one
even-odd path. "Unrot" is a working name; only the colours and the paths below are edition
specific.

Writes the general flavor's Android launcher layers, splash and brand vectors and pre-Android 8
PNGs into android/app/src/general/res. Requires Pillow. Usage: python3 design/app-icon/unrot_mark.py
"""
import hisn_mark as m

# Head: a circle of radius 30 around (54, 56), four cubic quarters.
m.BASE = ['M54 26 C70.57 26 84 39.43 84 56 C84 72.57 70.57 86 54 86 '
          'C37.43 86 24 72.57 24 56 C24 39.43 37.43 26 54 26 Z']
m.CUT = [
    # Stem: rounded foot, top slanting up into the right leaf.
    'M52 76 Q52 78 54 78 Q56 78 56 76 V55 L52 58 Z',
    # Left leaf, attached along the stem's left edge.
    'M52 68 C44 68 37 62 36 52 C46 52 52 58 52 65 Z',
    # Right leaf, higher and larger, attached along the stem's right edge.
    'M56 58 C56 46 63 37 74 36 C74 48 66 55 56 55 Z',
]
m.BACK = []
m.MARK_CX, m.MARK_CY = 54, 56

INK, PEARL = '#2B4A6F', '#F4F1EA'
LIGHT = dict(bg=PEARL, ink=INK, paper=PEARL)
SILHOUETTE = [(m.BASE + m.CUT, '#FFFFFFFF', True)]


def generated(text):
    return text.replace('Generated by design/app-icon/hisn_mark.py.',
                        'Generated by design/app-icon/unrot_mark.py.')


def main():
    res = 'android/app/src/general/res/'
    layers = [(m.BASE, INK, False), (m.CUT, PEARL, False)]
    m.write(res + 'drawable/ic_launcher_foreground.xml', generated(m.vector_drawable(
        'Unrot launcher foreground: ink head, pearl sprout.', layers, m.ANDROID_SCALE)))
    m.write(res + 'drawable/ic_launcher_monochrome.xml', generated(m.vector_drawable(
        'Unrot themed-icon layer: one silhouette, the sprout is a hole.', SILHOUETTE, m.ANDROID_SCALE)))
    m.write(res + 'drawable/ic_splash_mark.xml', generated(m.vector_drawable(
        'Unrot Android 12 splash: pearl head on the splash background.',
        [(m.BASE, PEARL, False), (m.CUT, INK, False)], m.ANDROID_SCALE)))
    m.write(res + 'drawable/ic_brand_mark.xml', generated(m.vector_drawable(
        'Unrot in-app brand mark, tinted at runtime: one silhouette cropped to the head.',
        SILHOUETTE, 1.0, viewport=68, size_dp=24)))
    for folder, px in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
        window = (18, 18, 72, 72)
        m.save(m.render(px, LIGHT, m.ANDROID_SCALE, window, mask='rounded'),
               f'{res}mipmap-{folder}/ic_launcher.png')
        m.save(m.render(px, LIGHT, m.ANDROID_SCALE, window, mask='circle'),
               f'{res}mipmap-{folder}/ic_launcher_round.png')
    m.save(m.render(1024, LIGHT, m.APPLE_SCALE), 'design/app-icon/Unrot-source.png', opaque=True)
    print('Exported the Unrot mark to the general edition.')


if __name__ == '__main__':
    main()
