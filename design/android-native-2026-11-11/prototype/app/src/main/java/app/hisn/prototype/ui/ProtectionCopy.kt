package app.hisn.prototype.ui

/**
 * Prototype copy for the two languages Hisn ships. The production port should use Android string
 * resources; this keeps the design prototype self-contained and lets the emulator show a true RTL
 * screen without changing the device locale.
 */
data class ProtectionCopy(
    val appName: String,
    val tagline: String,
    val navProtection: String,
    val navRules: String,
    val navSettings: String,
    val protectedTitle: String,
    val protectedBody: String,
    val partialTitle: String,
    val partialBody: String,
    val fixGaps: String,
    val attentionTitle: String,
    val attentionBody: String,
    val runCheck: String,
    val fixNow: String,
    val network: String,
    val apps: String,
    val images: String,
    val tags: String,
    val on: String,
    val off: String,
    val needsAttention: String,
    val dnsStoppedTitle: String,
    val dnsStoppedBody: String,
    val gapTitle: String,
    val gapBody: String,
    val layers: String,
    val dnsTitle: String,
    val dnsOn: String,
    val dnsOff: String,
    val appTitle: String,
    val appOff: String,
    val appNone: String,
    val appOne: String,
    val appMany: String,
    val tagsTitle: String,
    val tagsOn: String,
    val tagsOff: String,
    val imageTitle: String,
    val imageOn: String,
    val imageOff: String,
    val yourRules: String,
    val domains: String,
    val appsBlocked: String,
    val bypass: String,
    val reassurance: String,
    val checkPassed: String
) {
    /** "1 app blocked", "3 apps blocked", "No apps selected" — one phrase, not three strings. */
    fun appsBlockedText(count: Int): String = when {
        count <= 0 -> appNone
        count == 1 -> appOne
        else -> appMany.replace("{n}", count.toString())
    }
}

